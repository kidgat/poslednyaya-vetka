const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
function hash(x, y) {                     // детерминированный шум 0..1
  let h = Math.imul(x | 0, 374761393) + Math.imul(y | 0, 668265263) + Math.imul(CONFIG.SEED, 1442695041);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}
function noise1(t, seed = 0) {            // плавный одномерный шум 0..1
  const i = Math.floor(t), f = t - i, s = f * f * (3 - 2 * f);
  const a = hash(i, seed), b = hash(i + 1, seed);
  return a + (b - a) * s;
}
function makeRng(seed) {                  // mulberry32
  let a = seed >>> 0;
  return () => { a = (a + 0x6D2B79F5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
