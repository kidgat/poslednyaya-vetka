/** Рисует строку пиксельным шрифтом. Возвращает ширину. */
function drawText(g, str, x, y, color, shadow = null, scale = 1) {
  const pts = [];
  [...str.toUpperCase()].forEach((ch, i) => {
    const gl = FONT_SRC[ch]; if (!gl) return;
    for (let k = 0; k < 35; k++) if (gl[k] === '1') pts.push(x + (i * 6 + (k % 5)) * scale, y + ((k / 5) | 0) * scale);
  });
  if (shadow) { g.fillStyle = shadow; for (let i = 0; i < pts.length; i += 2) g.fillRect(pts[i], pts[i + 1] + scale, scale, scale); }
  g.fillStyle = color; for (let i = 0; i < pts.length; i += 2) g.fillRect(pts[i], pts[i + 1], scale, scale);
  return textWidth(str, scale);
}
const textWidth = (str, scale = 1) => ([...str].length * 6 - 1) * scale;
/** Табличка с надписью по центру cx. */
function plate(g, cx, y, str, bg, fg, rim) {
  const w = textWidth(str) + 10, x = Math.round(cx - w / 2);
  R(g, x - 1, y - 1, w + 2, 13, '#0d1012'); R(g, x, y, w, 11, bg); R(g, x, y, w, 1, rim);
  drawText(g, str, x + 5, y + 2, fg, 'rgba(0,0,0,.55)');
}

