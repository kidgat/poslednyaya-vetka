/** Линия по Брезенхэму толщиной `t` пикселей (по горизонтали). */
function L(g, x0, y0, x1, y1, c, t = 1) {
  x0 = Math.round(x0); y0 = Math.round(y0); x1 = Math.round(x1); y1 = Math.round(y1);
  g.fillStyle = c;
  const dx = Math.abs(x1 - x0), dy = -Math.abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1;
  let e = dx + dy;
  for (;;) {
    g.fillRect(x0 - (t >> 1), y0, t, 1);
    if (x0 === x1 && y0 === y1) break;
    const e2 = 2 * e; if (e2 >= dy) { e += dy; x0 += sx; } if (e2 <= dx) { e += dx; y0 += sy; }
  }
}
/** Провисающий кабель (цепная линия упрощённо — парабола). */
function cable(g, x0, x1, y, sag, c) {
  for (let x = x0; x <= x1; x++) { const t = (x - x0) / (x1 - x0); R(g, x, y + Math.round(sag * 4 * t * (1 - t)), 1, 1, c); }
}
/** Заливка круга построчно (пиксельный круг). */
function disc(g, cx, cy, r, c) {
  g.fillStyle = c;
  for (let y = -r; y <= r; y++) { const w = Math.round(Math.sqrt(r * r - y * y)); g.fillRect(cx - w, cy + y, w * 2 + 1, 1); }
}
/** Попиксельная «покраска» участка канваса функцией fn(x, y, out[r,g,b,a]) → true, если пиксель рисуется. */
function paintRegion(g, x0, y0, w, h, fn) {
  const m = g.getTransform(), ox = Math.round(m.e), oy = Math.round(m.f);   // 0.9: учитывает сдвиг (слой вестибюля, комнаты со сдвигом)
  const img = g.getImageData(x0 + ox, y0 + oy, w, h), d = img.data, out = [0, 0, 0, 255];
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    out[3] = 255;
    if (fn(x0 + x, y0 + y, out)) { const i = (y * w + x) * 4; d[i] = out[0]; d[i + 1] = out[1]; d[i + 2] = out[2]; d[i + 3] = out[3]; }
  }
  g.putImageData(img, x0 + ox, y0 + oy);
}
